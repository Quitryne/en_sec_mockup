var activeProjectKey = null;

function normalizeRoute(route) {
  if (!route) return "home";
  return route.replace(/^#/, "");
}

function renderProjectContext(projectKey) {
  var info = spaProjects[projectKey] || spaProjects.none;
  var nameNode = document.querySelector("[data-project-name]");
  var metaNode = document.querySelector("[data-project-meta]");
  var topbarNameNode = document.querySelector("[data-topbar-project-name]");
  var workspaceNameNode = document.querySelector("[data-workspace-project-name]");
  var workspaceMetaNode = document.querySelector("[data-workspace-project-meta]");
  if (nameNode) nameNode.textContent = info.name;
  if (metaNode) metaNode.textContent = info.meta;
  if (topbarNameNode) topbarNameNode.textContent = info.name;
  if (workspaceNameNode) workspaceNameNode.textContent = info.name;
  if (workspaceMetaNode) workspaceMetaNode.textContent = info.meta;
}

function renderProjectCardSelection(projectKey) {
  document.querySelectorAll("[data-project-card]").forEach(function (card) {
    var key = card.getAttribute("data-project-card");
    card.classList.toggle("selected", key === projectKey);
  });
}

function renderWorkspace(projectKey) {
  var info = spaProjects[projectKey] || spaProjects.none;
  var history = info.workspaceHistory || [];
  var presets = info.workspacePresets || [];
  for (var i = 0; i < 3; i += 1) {
    var titleNode = document.querySelector("[data-workspace-history-title-" + (i + 1) + "]");
    var descNode = document.querySelector("[data-workspace-history-desc-" + (i + 1) + "]");
    var presetNode = document.querySelector("[data-workspace-preset-" + (i + 1) + "]");
    if (titleNode) titleNode.textContent = history[i] ? history[i][0] : "";
    if (descNode) descNode.textContent = history[i] ? history[i][1] : "";
    if (presetNode) presetNode.textContent = presets[i] || "-";
  }
}

function renderPreview(projectKey) {
  var info = spaProjects[projectKey] || spaProjects.none;
  var titleNode = document.querySelector("[data-preview-doc-title]");
  var metaNode = document.querySelector("[data-preview-doc-meta]");
  var presetNode = document.querySelector("[data-preview-preset]");
  if (titleNode) titleNode.textContent = info.previewDocTitle || "";
  if (metaNode) metaNode.textContent = info.previewDocMeta || "";
  if (presetNode) presetNode.textContent = info.previewPreset || "-";

  var items = info.previewItems || [];
  var tags = info.previewTags || [];
  for (var i = 0; i < 4; i += 1) {
    var itemNode = document.querySelector("[data-preview-item-" + (i + 1) + "]");
    if (itemNode) itemNode.textContent = items[i] || "";
  }
  for (var j = 0; j < 2; j += 1) {
    var tagNode = document.querySelector("[data-preview-tag-" + (j + 1) + "]");
    if (tagNode) tagNode.textContent = tags[j] || "-";
  }
}

function renderExport(projectKey) {
  var info = spaProjects[projectKey] || spaProjects.none;
  var exportInfo = info.export || {};
  var mappings = [
    ["[data-export-doc-title]", exportInfo.docTitle || ""],
    ["[data-export-format]", exportInfo.format || "-"],
    ["[data-export-commentary]", exportInfo.commentary || "-"],
    ["[data-export-preset]", exportInfo.preset || "-"],
    ["[data-export-progress]", exportInfo.progress || "-"],
    ["[data-export-note]", exportInfo.note || ""]
  ];
  mappings.forEach(function (entry) {
    var node = document.querySelector(entry[0]);
    if (node) node.textContent = entry[1];
  });
}

function setActiveNav(route) {
  document.querySelectorAll("[data-route-link]").forEach(function (link) {
    var target = link.getAttribute("data-route-link");
    link.classList.toggle("active", target === route);
  });

  document.querySelectorAll(".nav-item-expandable").forEach(function (menu) {
    var hasActiveChild = menu.querySelector(".nav-subitem.active");
    if (hasActiveChild) {
      menu.classList.add("open");
    }
  });
}

function setActivePage(route) {
  var pages = document.querySelectorAll(".spa-page");
  var found = false;
  pages.forEach(function (page) {
    var match = page.getAttribute("data-route") === route;
    page.classList.toggle("active", match);
    if (match) found = true;
  });

  if (!found) {
    route = "home";
    pages.forEach(function (page) {
      page.classList.toggle("active", page.getAttribute("data-route") === route);
    });
  }

  var activePage = document.querySelector('.spa-page.active');
  var title = activePage ? activePage.getAttribute("data-title") : "영어비서 SPA";
  var crumb = activePage ? activePage.getAttribute("data-crumb") : "Mock-up";
  var titleNode = document.querySelector("[data-spa-title]");
  var crumbNode = document.querySelector("[data-spa-crumb]");
  if (titleNode) titleNode.textContent = title;
  if (crumbNode) crumbNode.textContent = crumb;

  if (!activeProjectKey) {
    activeProjectKey = routeProjectMap[route] || "none";
  } else if (route === "projects") {
    activeProjectKey = "none";
  } else if (!spaProjects[activeProjectKey]) {
    activeProjectKey = routeProjectMap[route] || "none";
  }

  if (route !== "projects" && activeProjectKey === "none") {
    activeProjectKey = routeProjectMap[route] || "none";
  }

  renderProjectContext(activeProjectKey);
  renderProjectCardSelection(activeProjectKey);
  renderWorkspace(activeProjectKey);
  renderPreview(activeProjectKey);
  renderExport(activeProjectKey);
  setActiveNav(route);
}

function navigate(route) {
  var normalized = normalizeRoute(route);
  if (location.hash !== "#" + normalized) {
    location.hash = normalized;
    return;
  }
  setActivePage(normalized);
}

function bindRouteLinks() {
  document.querySelectorAll("[data-route-link]").forEach(function (link) {
    link.addEventListener("click", function (event) {
      var route = link.getAttribute("data-route-link");
      var projectKey = link.getAttribute("data-project-key");
      if (!route) return;
      event.preventDefault();
      if (projectKey && spaProjects[projectKey]) {
        activeProjectKey = projectKey;
      } else if (route === "projects") {
        activeProjectKey = "none";
      }
      navigate(route);
    });
  });
}

function bindProjectCards() {
  document.querySelectorAll("[data-project-card]").forEach(function (card) {
    function openFromCard() {
      var projectKey = card.getAttribute("data-project-card");
      var route = card.getAttribute("data-project-route") || "projects";
      if (projectKey && spaProjects[projectKey]) {
        activeProjectKey = projectKey;
      }
      navigate(route);
    }

    card.addEventListener("click", function (event) {
      if (event.target.closest("[data-route-link], button, a, input, select, textarea")) {
        return;
      }
      openFromCard();
    });

    card.addEventListener("keydown", function (event) {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openFromCard();
      }
    });
  });
}

